public class MTProtoSession {
    [StructLayout(LayoutKind.Sequential, Pack = 1)]
    public struct Message {
        public long AuthKeyId;
        public long MessageId;
        public uint MessageLength;
    }
    private readonly ITransport _transport;
    
    private bool _disposeStream;
    public long AuthKeyId = 0;
    private RandomNumberGenerator _rng;
    public MTProtoSession(ITransport transport) : this(transport, RandomNumberGenerator.Create()) {}
    public MTProtoSession(ITransport transport, RandomNumberGenerator randomSource) {
        _transport = transport;
        _rng = randomSource;
    }

    private uint _messageId = 0;
    public long GenerateMessageId(DateTimeOffset date) => (date.ToUnixTimeSeconds() << 32) + (_messageId++ * 4);
    public long GenerateMessageId() => GenerateMessageId(DateTimeOffset.UtcNow);

    public void Connect() {
        var reqPq = InitiateDhExchange();
        SendDhParam(reqPq);
    }

    private void SendDhParam(resPQ resPq) {
        var pof = ProofOfWork(resPq.pq);
        if (!TelegramRsaKeys.TryFindKey(resPq.ServerPublicKeyFingerprints, out var selectedKey))
            throw new InvalidOperationException($"No matching server public key found. Suggested {string.Join(", ", resPq.ServerPublicKeyFingerprints.Select(arg => arg.ToString("x")))}");
        if (selectedKey is null)
            throw new NullReferenceException("the found key was null");
        Span<byte> newnonce = stackalloc byte[32]; 
        _rng.GetBytes(newnonce);
        var innerData = new PqInnerDataDc(resPq.pq, pof.P, pof.Q, resPq.Nonce, resPq.ServerNonce, newnonce, 2);
        var serializedInnerData = ((ITlType)innerData).Serialize(); // why csharp like that?
        var encryptedInnerData = selectedKey.Value.Rsa.EncryptRsaPad(serializedInnerData);
        var outerData = new ReqDhParams(resPq.Nonce, resPq.ServerNonce, pof.P, pof.Q,
            unchecked((long)selectedKey.Value.Fingerprint), encryptedInnerData);
        var outerDataSerialized = ((ITlType)outerData).Serialize();
        SendPlaintext(outerDataSerialized);
        var result = ReceivePlaintext();
        var id = BinaryPrimitives.ReadInt32LittleEndian(result.Span);
        if (id == TlError.Id) {
            var res = TlError.Deserialize(result.Span, out _);
            throw new Exception($"Telegram returned error {res.Code}: {res.Text}");
        }
        throw new NotImplementedException();
    }

    private ref struct resPQ {
        /// <summary>
        /// resPQ constructor number from TL schema
        /// </summary>
        public int ID;
        /// <summary>
        /// Value generated by client
        /// </summary>
        public ReadOnlySpan<byte> Nonce;
        /// <summary>
        /// Server-generated random number
        /// </summary>
        public ReadOnlySpan<byte> ServerNonce;
        /// <summary>
        /// Single-byte prefix denoting length, an 8-byte string, and three bytes of padding
        /// </summary>
        public ulong pq;
        /// <summary>
        /// 64 lower-order bits of SHA1(server_public_key)
        /// </summary>
        public ulong[] ServerPublicKeyFingerprints;

        public resPQ(ReadOnlyMemory<byte> response) {
            var reader = new TlReader(response);
            ID = reader.ReadAlignedSigned();
            Nonce = reader.ReadRangeAligned(16);
            // The value of server_nonce is selected randomly by the server; following this step, it is known to all.
            ServerNonce = reader.ReadRangeAligned(16);
            //Here, string pq is a representation of a natural number (in binary big endian format). This number is the
            //product of two different odd prime numbers. Normally, pq is less than or equal to 2^63-1.
            pq = BinaryPrimitives.ReadUInt64BigEndian(reader.ReadString());
        
            ServerPublicKeyFingerprints = reader.ReadVector<ulong>();
        }
    }
    
    private unsafe resPQ InitiateDhExchange() {
        // TODO: use generated req_pq_multi constructor number from TL schema
        Span<byte> nonce = stackalloc byte[20];
        BitConverter.TryWriteBytes(nonce[..4], 0xbe7e8ef1); // req_pq_multi id
        
        // The value of nonce is selected randomly by the client (random number) and identifies the client within this communication.
        // Following this step, it is known to all.
        _rng.GetBytes(nonce[4..20]);
        
        SendPlaintext(nonce);
        
        Console.WriteLine("awaiting response");
        
        var reg_pq = new resPQ(ReceivePlaintext());
        if (!reg_pq.Nonce.SequenceEqual(nonce[4..20])) {
            throw new Exception(
                $"Received nonce is different than sent! MITM? Recv:{Convert.ToHexString(reg_pq.Nonce)} Sent {Convert.ToHexString(nonce[4..20])}");
        }

        return reg_pq;
    }
    
    /// <summary>
    /// Decomposes a semiprime n into its two prime cofactors (p, q).
    /// </summary>
    private static (ulong P, ulong Q) ProofOfWork(ulong n) {
        if (n % 2 == 0)
            return (2, n / 2);

        ulong c = 1;
        while (true) {
            ulong x = 2;
            ulong y = 2;
            ulong d = 1;
            
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            ulong Next(ulong val) => (ulong)(((Int128)val * val + c) % n);

            while (d == 1) {
                x = Next(x);
                y = Next(Next(y));

                var diff = x > y ? x - y : y - x;
                d = Gcd(diff, n);
            }

            if (d != n) {
                var p = Math.Min(d, n / d);
                var q = Math.Max(d, n / d);
                return (p, q);
            }

            c++;
        }
    }

    private static ulong Gcd(ulong a, ulong b) {
        while (b != 0) {
            var temp = b;
            b = a % b;
            a = temp;
        }
        return a;
    }

    /// <summary>
    /// Sent the payload with plain text
    /// </summary>
    public void SendPlaintext(ReadOnlySpan<byte> buffer) {
        var nonce = new byte[20+buffer.Length];
        MemoryMarshal.Write(nonce, new Message {
            AuthKeyId = 0,
            MessageId = GenerateMessageId(),
            MessageLength = (uint)buffer.Length
        });
        buffer.CopyTo(nonce.AsSpan(20..));
        _transport.Send(nonce);
    }

    public void SendPlaintext(byte[] buffer, int offset, int count) => SendPlaintext(buffer.AsSpan(offset..count));


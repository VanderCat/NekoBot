    public ReadOnlyMemory<byte> ReceivePlaintext() {
        var raw = _transport.Receive();
        var authKeyId = MemoryMarshal.Read<long>(raw.Span);
        if (authKeyId != 0) 
            throw new InvalidDataException("The following response is not in a plaintext format");
        // TODO: check message id: server message identifiers modulo 4 yield 1 if the message is a response to a client
        //       message, and 3 otherwise

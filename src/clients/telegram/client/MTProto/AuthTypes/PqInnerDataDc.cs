using System.Buffers.Binary;
using System.Diagnostics;
using NekoBot.Telegram;

namespace NekoBot.Adapter.Telegram.MTProto.AuthTypes;

internal class PqInnerDataDc : ITlBoxedType<PqInnerDataDc> { 
    /// <summary>
    /// p_q_inner_data_dc constructor number from TL schema
    /// </summary>
    public static int Id => unchecked((int)0xa9f55f95);
    /// <summary>
    /// Big endian.
    /// </summary>
    public TlString Pq;
    /// <summary>
    /// First prime cofactor. Big endian.
    /// </summary>
    public TlString P;
    /// <summary>
    /// Second prime cofactor. Big endian.
    /// </summary>
    public TlString Q;
    /// <summary>
    /// Value generated by client in Step 1
    /// </summary>
    public Memory<byte> Nonce;
    /// <summary>
    /// Value received from server in Step 2
    /// </summary>
    public Memory<byte> ServerNonce;
    /// <summary>
    /// Client-generated random number
    /// </summary>
    public Memory<byte> NewNonce;

    /// <summary>
    /// DC ID.
    /// </summary>
    /// <remarks>
    /// <p>10000 (decimal) has to be added to the DC ID to connect to the test servers.</p>
    /// <p>It has to be made negative if the DC we're connecting to is a media (not CDN) DC.</p>
    /// </remarks>
    public int DC;

    public PqInnerDataDc(ulong pq, ulong p, ulong q, ReadOnlySpan<byte> nonce, ReadOnlySpan<byte> serverNonce, ReadOnlySpan<byte> newNonce, int dc) {
        Pq = new(TgUtils.ToBigEndianBytes(pq));
        P = new(TgUtils.ToBigEndianBytes((uint)p));
        Q = new(TgUtils.ToBigEndianBytes((uint)q));
        Debug.Assert(nonce.Length == 16);
        Nonce = nonce.ToArray();
        Debug.Assert(serverNonce.Length == 16);
        ServerNonce = serverNonce.ToArray();
        Debug.Assert(newNonce.Length == 32);
        NewNonce = newNonce.ToArray();
        DC = dc;
    }

    public int Serialize(Span<byte> destination) {
        Debug.Assert(destination.Length >= GetSerializedLength());
        return new TlLightWriter(destination)
            .WriteIdOf<PqInnerDataDc>()
            .WriteString(Pq)
            .WriteString(P)
            .WriteString(Q)
            .WriteBytes(Nonce)
            .WriteBytes(ServerNonce)
            .WriteBytes(NewNonce)
            .WriteInt(DC)
            .Counter;
    }
    
    public int GetSerializedLength() {
        return 8 + Pq.GetSerializedLength() + P.GetSerializedLength() + Q.GetSerializedLength() + Nonce.Length +
               ServerNonce.Length + NewNonce.Length;
    }
    
    public static PqInnerDataDc Deserialize(ReadOnlySpan<byte> data, out int bytesRead) {
        throw new NotImplementedException(); // probably wont be ever needed as this is only sent on server
    }
}
namespace NekoBot.Telegram.MTProto.AuthTypes.Server;

public class DhInnerData : ITlBoxedType<DhInnerData> {
    public static int Id => unchecked((int)0xb5890dba);
    /// <summary>
    /// Value generated by client in Step 1
    /// </summary>
    public Memory<byte> Nonce;
    /// <summary>
    /// Value received from server in Step 2
    /// </summary>
    public Memory<byte> ServerNonce;
    /// <summary>
    /// Value received from server in Step 2
    /// </summary>
    public int G;
    /// <summary>
    /// 2048-bit prime, in big-endian byte order, to be checked as specified in the auth key docs
    /// </summary>
    public TlString DhPrime;
    /// <summary>
    /// g_a diffie-hellman parameter
    /// </summary>
    public TlString Ga;
    /// <summary>
    /// Server time
    /// </summary>
    public int ServerTime;
    public int Serialize(Span<byte> destination) {
        return new TlLightWriter(destination)
            .WriteIdOf<DhInnerData>()
            .WriteBytes(Nonce)
            .WriteBytes(ServerNonce)
            .WriteInt(G)
            .WriteString(DhPrime)
            .WriteString(Ga)
            .WriteInt(ServerTime)
            .Counter;
    }

    public int GetSerializedLength() => 4+16 + 16 + 4 + DhPrime.GetSerializedLength() + Ga.GetSerializedLength() + 4;
    public static DhInnerData Deserialize(ReadOnlySpan<byte> data, out int bytesRead) {
        bytesRead = 0;
        var reader = new TlLightReader(data, ref bytesRead);
        reader.ThrowIfNotIdOf<DhInnerData>();
        var res = new DhInnerData {
            Nonce = reader.ConsumeBytes(16).ToArray(),
            ServerNonce = reader.ConsumeBytes(16).ToArray(),
            G = reader.ConsumeInt(),
            DhPrime = reader.ConsumeString(),
            Ga = reader.ConsumeString(),
            ServerTime = reader.ConsumeInt(),
        };
        return res;
    }
}
namespace NekoBot.Telegram.MTProto.AuthTypes;

public class ReqDhParams : ITlBoxedType<ReqDhParams> {
    public static int Id => unchecked((int)0xd712e4be);
    /// <summary>
    /// Value generated by client in Step 1
    /// </summary>
    public Memory<byte> Nonce;
    /// <summary>
    /// Value received from server in Step 2
    /// </summary>
    public Memory<byte> ServerNonce;

    public TlString P;
    public TlString Q;
    public long PublicKeyFingerprint;
    public TlString EncryptedData;

    public ReqDhParams(ReadOnlySpan<byte> nonce, ReadOnlySpan<byte> serverNonce, TlString p, TlString q, long publicKeyFingerprint,
        TlString encryptedData) {
        Nonce = nonce.ToArray();
        ServerNonce = serverNonce.ToArray();
        P = p;
        Q = q;
        EncryptedData = encryptedData;
    }

    public ReqDhParams(ReadOnlySpan<byte> nonce, ReadOnlySpan<byte> serverNonce, ulong p, ulong q, long publicKeyFingerprint, ReadOnlySpan<byte> encryptedData) {
        Nonce = nonce.ToArray();
        ServerNonce = serverNonce.ToArray();
        P = new(TgUtils.ToBigEndianBytes((uint)p));
        Q = new(TgUtils.ToBigEndianBytes((uint)q));
        PublicKeyFingerprint = publicKeyFingerprint;
        EncryptedData = new(encryptedData);
    }

    public int Serialize(Span<byte> destination) {
        var writer = new TlLightWriter(destination);
        return writer
            .WriteIdOf<ReqDhParams>()
            .WriteBytes(Nonce)
            .WriteBytes(ServerNonce)
            .WriteString(P)
            .WriteString(Q)
            .WriteLong(PublicKeyFingerprint)
            .WriteString(EncryptedData)
            .Counter;
    }

    public int GetSerializedLength() => 4 + Nonce.Length + ServerNonce.Length +
                                        P.GetSerializedLength() + Q.GetSerializedLength() + 8 +
                                        EncryptedData.GetSerializedLength();
    public static ReqDhParams Deserialize(ReadOnlySpan<byte> data, out int bytesRead) {
        bytesRead = 0;
        var reader = new TlLightReader(data, ref bytesRead);
        reader.ThrowIfNotIdOf<ReqDhParams>();
        return new ReqDhParams (
            reader.ConsumeBytes(16),
            reader.ConsumeBytes(16),
            reader.ConsumeString(),
            reader.ConsumeString(),
            reader.ConsumeLong(),
            reader.ConsumeString()
        );
    }
    
}